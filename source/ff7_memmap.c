/*
 * Faster x86 address translation for libjni_ff7.so.
 *
 * The recompiled ff7.exe reaches every byte of x86 memory through
 * mk_address(va) = MEMMAP[va >> 12] + (va & 0xfff), MEMMAP being the 4 KB
 * page table filled by VA_newMapper(). The .so has 669,918 calls to it -
 * about one every 8 instructions of recompiled code - which makes it the most
 * executed function of the game thread (the x86 registers live in memory, so
 * even a `push ebp` goes through it).
 *
 * Two changes, both producing exactly the addresses the original would:
 *
 *  1. mk_address is rewritten in place. The original loads MEMMAP's address
 *     from a literal and then from the GOT before indexing the table (two
 *     dependent loads on every call); the new body has the address as a
 *     movw/movt constant. The unmapped-page path still returns the same dummy
 *     page and a null address still goes to the original error path. Checked
 *     at startup on a scratch page; on a mismatch the original is restored.
 *
 *  2. Constant addresses (x86 globals: `movw r0, #lo / movt r0, #hi /
 *     bl mk_address`, 71,246 sites listed in ff7_memmap_sites.bin by
 *     scripts/gen-memmap-sites.py) are translated once: the movw/movt get the
 *     host address and the bl becomes a nop. This runs when the game thread
 *     calls manage_import(), right after create_pe_mappers() has mapped
 *     ff7.exe and before any recompiled code runs. A mapped page never moves
 *     (VA_newMapper only fills empty MEMMAP entries, VA_init runs once
 *     before), and only the game thread runs recompiled functions, so the
 *     patched code cannot race or go stale. Every site is checked against the
 *     expected instructions first; sites whose page is not mapped yet keep
 *     the call.
 *
 * Creating DATA_PATH "memmap_off.txt" turns both off (for A/B comparisons).
 *
 * This software may be modified and distributed under the terms
 * of the MIT license. See the LICENSE file for details.
 */

