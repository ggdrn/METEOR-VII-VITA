extern so_module so_mod;

// Generated by CMake from source/ff7_memmap_sites.bin
extern const uint8_t ff7_memmap_sites[];
extern const uint32_t ff7_memmap_sites_size;

#define OFF_SWITCH        DATA_PATH "memmap_off.txt"
#define SYM_MK_ADDRESS    "mk_address"
#define SYM_MEMMAP        "MEMMAP"
#define SYM_MANAGE_IMPORT "_Z13manage_importv"
#define MK_ADDRESS_OFFSET 0x93d714
#define MEMMAP_GOT        0xf4c898 // GOT slot mk_address reads: &MEMMAP
#define DUMMY_GOT         0xf4c8ac // GOT slot: page returned for unmapped addresses
#define DUMMY_LITERAL     0x34     // mk_address literal used only by the unmapped path
#define DUMMY_LITERAL_VAL 0x0060f17a
#define BODY_HALFWORDS    16       // mk_address+0x00..0x1f (the null path at +0x20 stays)
#define MAX_BAD_SITES     64       // more mismatches than this: not the expected .so
#define TEST_PAGE         0xfffffu // scratch MEMMAP entry for the startup check

typedef uint8_t * (* mk_address_fn)(uint32_t va);

static const uint16_t mk_original[BODY_HALFWORDS] = {
    0xb170,         // cbz    r0, null
    0x4b0b,         // ldr    r3, [pc, #0x2c]
    0x0b02,         // lsrs   r2, r0, #12
    0x447b,         // add    r3, pc
    0x681b,         // ldr    r3, [r3]              ; &MEMMAP, from the GOT
    0xf853, 0x3022, // ldr.w  r3, [r3, r2, lsl #2]
    0xb11b,         // cbz    r3, unmapped
    0xf3c0, 0x000b, // ubfx   r0, r0, #0, #12
    0x4418,         // add    r0, r3
    0x4770,         // bx     lr
    0x4806,         // unmapped: ldr r0, [pc, #0x18]
    0x4478,         // add    r0, pc
    0x6800,         // ldr    r0, [r0]              ; dummy page, from the GOT
    0x4770,         // bx     lr
};

static uint16_t * mk_code;
static uint32_t * memmap;
static uint32_t dummy_page;
static so_hook import_hook;

/*
 * Thumb-2 encodings
 */
// movw/movt rd, #imm16 (T3/T1)
static void encode_mov16(uint16_t * hw, int top, int rd, uint16_t imm) {
    hw[0] = (top ? 0xf2c0 : 0xf240) | ((imm >> 1) & 0x400) | (imm >> 12);
    hw[1] = ((imm << 4) & 0x7000) | (rd << 8) | (imm & 0xff);
}

// movw/movt r0, #imm16: returns 1 and the immediate if `hw` is one
static int decode_mov16_r0(const uint16_t * hw, int top, uint16_t * imm) {
    if ((hw[0] & 0xfbf0) != (top ? 0xf2c0 : 0xf240) || (hw[1] & 0x8f00) != 0) return 0;
    *imm = ((hw[0] & 0xf) << 12) | ((hw[0] & 0x400) << 1) | ((hw[1] & 0x7000) >> 4) | (hw[1] & 0xff);
    return 1;
}

// bl (T1): target address, or 0 if `hw` is not a bl
static uintptr_t decode_bl(const uint16_t * hw) {
    if ((hw[0] & 0xf800) != 0xf000 || (hw[1] & 0xd000) != 0xd000) return 0;
    uint32_t s = (hw[0] >> 10) & 1, j1 = (hw[1] >> 13) & 1, j2 = (hw[1] >> 11) & 1;
    uint32_t off = (s << 24) | ((!(j1 ^ s)) << 23) | ((!(j2 ^ s)) << 22)
                 | ((hw[0] & 0x3ffu) << 12) | ((hw[1] & 0x7ffu) << 1);
    if (s) off |= 0xfe000000u;
    return (uintptr_t) hw + 4 + off;
}

static void write_code(void * dst, const void * src, size_t len) {
    profiler_hold();
    sceClibMemcpy(dst, src, len);
    kuKernelFlushCaches(dst, len);
    profiler_release();
}

/*
 * 1. mk_address body
 */
static int fast_body_selftest(void) {
    static uint8_t page[0x1000];
    mk_address_fn mk = (mk_address_fn) ((uintptr_t) mk_code | 1);
    uint32_t saved = memmap[TEST_PAGE];

    memmap[TEST_PAGE] = (uint32_t) page;
    uint8_t * mapped = mk((TEST_PAGE << 12) | 0x123);
    memmap[TEST_PAGE] = 0;
    uint8_t * unmapped = mk((TEST_PAGE << 12) | 0x123);
    memmap[TEST_PAGE] = saved;

    if (mapped == page + 0x123 && (uint32_t) unmapped == dummy_page) return 1;
    l_error("ff7_memmap: mk_address selftest MISMATCH (mapped %p, expected %p; unmapped %p, expected 0x%08x)",
            mapped, page + 0x123, unmapped, dummy_page);
    return 0;
}

static void install_fast_body(void) {
    uint16_t body[BODY_HALFWORDS];
    encode_mov16(body + 0, 0, 3, (uint32_t) memmap & 0xffff); // movw r3, #lo16(MEMMAP)
    encode_mov16(body + 2, 1, 3, (uint32_t) memmap >> 16);    // movt r3, #hi16(MEMMAP)
    body[4] = 0x0b02;                                         // lsrs   r2, r0, #12
    body[5] = 0xf853; body[6] = 0x3022;                       // ldr.w  r3, [r3, r2, lsl #2]
    body[7] = 0xb11b;                                         // cbz    r3, +0x18
    body[8] = 0xf3c0; body[9] = 0x000b;                       // ubfx   r0, r0, #0, #12
    body[10] = 0x4418;                                        // add    r0, r3
    body[11] = 0x4770;                                        // bx     lr
    body[12] = 0xb110;                                        // +0x18: cbz r0, +0x20 (null path)
    body[13] = 0x4806;                                        // ldr    r0, [pc, #0x18] ; literal +0x34
    body[14] = 0x4770;                                        // bx     lr
    body[15] = 0xbf00;                                        // nop

    uint32_t * literal = (uint32_t *) ((uint8_t *) mk_code + DUMMY_LITERAL);
    write_code(literal, &dummy_page, sizeof(dummy_page)); // was a GOT offset; now the page itself
    write_code(mk_code, body, sizeof(body));

    if (fast_body_selftest()) {
        l_info("ff7_memmap: fast mk_address installed (MEMMAP at %p, dummy page 0x%08x)", memmap, dummy_page);
    } else {
        uint32_t lit = DUMMY_LITERAL_VAL;
        write_code(mk_code, mk_original, sizeof(mk_original));
        write_code(literal, &lit, sizeof(lit));
        l_error("ff7_memmap: original mk_address restored");
    }
}

/*
 * 2. Constant-address call sites
 */
static uint32_t read_varint(const uint8_t ** p, const uint8_t * end) {
    uint32_t v = 0;
    for (int shift = 0; *p < end && shift < 32; shift += 7) {
        uint8_t b = *(*p)++;
        v |= (uint32_t) (b & 0x7f) << shift;
        if (!(b & 0x80)) break;
    }
    return v;
}

// pass 0 only checks; pass 1 patches. Returns the number of sites that do not
// match the expected instructions (pass 0) or that were patched (pass 1).
static unsigned walk_sites(int pass, unsigned * unmapped) {
    const uint8_t * p = ff7_memmap_sites + 8, * end = ff7_memmap_sites + ff7_memmap_sites_size;
    const uintptr_t text = so_mod.text_base, text_end = text + so_mod.text_size;
    const uintptr_t mk = (uintptr_t) mk_code;
    unsigned n = 0;
    uintptr_t bl = text;

    while (p < end) {
        bl += read_varint(&p, end) * 2;
        if (end - p < 2) break;
        uintptr_t movw = bl - p[0] * 2, movt = bl - p[1] * 2;
        p += 2;

        uint16_t lo, hi;
        int ok = movw >= text && movw < movt && movt < bl && bl + 4 <= text_end
              && decode_mov16_r0((uint16_t *) movw, 0, &lo)
              && decode_mov16_r0((uint16_t *) movt, 1, &hi)
              && decode_bl((uint16_t *) bl) == mk;
        if (pass == 0) {
            if (!ok) n++;
            continue;
        }
        if (!ok) continue;

        uint32_t va = (uint32_t) hi << 16 | lo;
        uint32_t page = memmap[va >> 12];
        if (!page) {
            (*unmapped)++;
            continue;
        }
        uint32_t host = page + (va & 0xfff);
        static const uint16_t nop_w[2] = { 0xf3af, 0x8000 };
        encode_mov16((uint16_t *) movw, 0, 0, host & 0xffff);
        encode_mov16((uint16_t *) movt, 1, 0, host >> 16);
        memcpy((void *) bl, nop_w, sizeof(nop_w));
        n++;
    }
    return n;
}

static void patch_constant_sites(void) {
    uint32_t count = 0;
    if (ff7_memmap_sites_size < 8 || memcmp(ff7_memmap_sites, "MKS1", 4)) {
        l_warn("ff7_memmap: site table missing or invalid, constant addresses not resolved");
        return;
    }
    memcpy(&count, ff7_memmap_sites + 4, 4);

    SceUInt64 t0 = sceKernelGetProcessTimeWide();
    unsigned bad = walk_sites(0, NULL);
    if (bad > MAX_BAD_SITES) {
        l_warn("ff7_memmap: %u of %u sites differ from v1.0.29, constant addresses not resolved", bad, count);
        return;
    }
    unsigned unmapped = 0;
    profiler_hold();
    unsigned patched = walk_sites(1, &unmapped);
    kuKernelFlushCaches((void *) so_mod.text_base, so_mod.text_size);
    profiler_release();
    l_info("ff7_memmap: %u of %u constant-address mk_address calls removed (%u not matching, %u unmapped) in %llu ms",
           patched, count, bad, unmapped, (sceKernelGetProcessTimeWide() - t0) / 1000);
}

// manage_import() follows create_pe_mappers() in main_ff7(), on the game thread
static void manage_import_hook(void) {
    write_code((void *) import_hook.addr, import_hook.orig_instr, sizeof(import_hook.orig_instr));
    patch_constant_sites();
    ((void (*)(void)) import_hook.thumb_addr)();
}

void ff7_memmap_patch(void) {
    if (file_exists(OFF_SWITCH)) {
        l_info("ff7_memmap: disabled by %s", OFF_SWITCH);
        return;
    }

    uintptr_t mk = so_symbol(&so_mod, SYM_MK_ADDRESS) & ~1;
    uintptr_t table = so_symbol(&so_mod, SYM_MEMMAP);
    uintptr_t import = so_symbol(&so_mod, SYM_MANAGE_IMPORT);
    if (mk != so_mod.text_base + MK_ADDRESS_OFFSET || !table || !import
        || memcmp((void *) mk, mk_original, sizeof(mk_original))
        || *(uint32_t *) (mk + DUMMY_LITERAL) != DUMMY_LITERAL_VAL
        || *(uint32_t *) (so_mod.text_base + MEMMAP_GOT) != table) {
        l_warn("ff7_memmap: unexpected .so layout, mk_address left alone");
        return;
    }
    mk_code = (uint16_t *) mk;
    memmap = (uint32_t *) table;
    dummy_page = *(uint32_t *) (so_mod.text_base + DUMMY_GOT);

    install_fast_body();
    import_hook = hook_addr(import, (uintptr_t) &manage_import_hook);
}
