extern so_module so_mod;

// Generated by CMake from source/ff7_stack_sites.bin
extern const uint8_t ff7_stack_sites[];
extern const uint32_t ff7_stack_sites_size;

#define OFF_SWITCH      DATA_PATH "stack_off.txt"
#define CHECK_SWITCH    DATA_PATH "stack_check.txt"
#define SYM_START       "_Z14start_ff7_corejjjj"
#define SYM_MK_ADDRESS  "mk_address"
#define SYM_MEMMAP      "MEMMAP"
#define START_PROLOGUE  0x43f8e92d // push.w {r3-r9, lr}
#define MK_ADDRESS_OFFSET 0x93d714
#define DUMMY_GOT       0xf4c8ac   // GOT slot: page mk_address returns for unmapped addresses
// main_ff7() code that runs once, before it calls start_ff7_core(): free for
// the check mode's veneer once start_ff7_core has been entered
#define VENEER          0x93f3f0
#define VENEER_CODE0    0x4c366812
#define VENEER_CODE1    0x60106019

#define STACK_VA        0x170000u
#define STACK_SIZE      0x20000u
#define STACK_TOP       (STACK_VA + STACK_SIZE)
#define GUARD           0x8000u
#define BLOCK_SIZE      (STACK_SIZE + 2 * GUARD)
#define MAX_BAD_SITES   64
#define MAX_REPORTS     32

static so_hook start_hook;
static uint32_t * memmap;
static uint32_t dummy_page;
static uintptr_t mk;
static uint32_t stack_k;

static struct { uintptr_t ret; uint32_t va; unsigned count; } reports[MAX_REPORTS];
static int report_count;
static unsigned long long off_stack_calls;

/*
 * Thumb-2 encodings
 */
static uintptr_t decode_bl(const uint16_t * hw) {
    if ((hw[0] & 0xf800) != 0xf000 || (hw[1] & 0xd000) != 0xd000) return 0;
    uint32_t s = (hw[0] >> 10) & 1, j1 = (hw[1] >> 13) & 1, j2 = (hw[1] >> 11) & 1;
    uint32_t off = (s << 24) | ((!(j1 ^ s)) << 23) | ((!(j2 ^ s)) << 22)
                 | ((hw[0] & 0x3ffu) << 12) | ((hw[1] & 0x7ffu) << 1);
    if (s) off |= 0xfe000000u;
    return (uintptr_t) hw + 4 + off;
}

static void encode_bl(uint16_t * hw, uintptr_t target) {
    int32_t off = (int32_t) (target - ((uintptr_t) hw + 4));
    uint32_t s = (off >> 24) & 1, i1 = (off >> 23) & 1, i2 = (off >> 22) & 1;
    uint32_t j1 = !(i1 ^ s), j2 = !(i2 ^ s);
    hw[0] = 0xf000 | (s << 10) | ((off >> 12) & 0x3ff);
    hw[1] = 0xd000 | (j1 << 13) | (j2 << 11) | ((off >> 1) & 0x7ff);
}

// add.w r0, r0, #K for K = B << 24, B >= 0x80 (modified immediate, rotation 8)
static void encode_add_k(uint16_t * hw, uint32_t k) {
    hw[0] = 0xf100;
    hw[1] = 0x4000 | ((k >> 24) & 0x7f);
}

/*
 * Check mode
 */
__attribute__((noinline)) static uint8_t * stack_check(uint32_t va) {
    if (va - STACK_VA >= STACK_SIZE) {
        uintptr_t ret = (uintptr_t) __builtin_return_address(0);
        off_stack_calls++;
        int i;
        for (i = 0; i < report_count && reports[i].ret != ret; i++)
            ;
        if (i == report_count && report_count < MAX_REPORTS) {
            reports[report_count++] = (typeof(reports[0])) { ret, va, 1 };
            l_warn("ff7_stack: site so+0x%x accessed VA 0x%08x, not on the stack (kept correct)",
                   (unsigned) (ret - 5 - so_mod.text_base), va);
        } else if (i < report_count) {
            reports[i].count++;
        }
    }
    uint32_t page = memmap[va >> 12];
    return (uint8_t *) (page ? page + (va & 0xfff) : dummy_page);
}

/*
 * Stack block
 */
static int map_stack(void) {
    for (uint32_t b = 0x9b; b <= 0xdf; b++) {
        uint32_t k = b << 24;
        uint32_t base = k + STACK_VA - GUARD;
        SceKernelAllocMemBlockKernelOpt opt;
        memset(&opt, 0, sizeof(opt));
        opt.size = sizeof(opt);
        opt.attr = 0x1; // fixed virtual address in field_C
        opt.field_C = base;
        SceUID uid = kuKernelAllocMemBlock("x86_stack", SCE_KERNEL_MEMBLOCK_TYPE_USER_RW, BLOCK_SIZE, &opt);
        if (uid < 0) continue;
        kuKernelMemProtect((void *) base, BLOCK_SIZE, KU_KERNEL_PROT_READ | KU_KERNEL_PROT_WRITE);
        memset((void *) base, 0, BLOCK_SIZE);

        for (uint32_t va = STACK_VA; va < STACK_TOP; va += 0x1000) {
            if (memmap[va >> 12]) {
                l_warn("ff7_stack: stack page 0x%x already mapped, stack accesses left alone", va);
                return 0;
            }
        }
        for (uint32_t va = STACK_VA; va < STACK_TOP; va += 0x1000)
            memmap[va >> 12] = va + k;
        stack_k = k;
        l_info("ff7_stack: x86 stack 0x%x-0x%x at %p (host = va + 0x%08x)", STACK_VA, STACK_TOP,
               (void *) (STACK_VA + k), k);
        return 1;
    }
    l_warn("ff7_stack: no fixed address free for the stack block, stack accesses left alone");
    return 0;
}

/*
 * Call sites
 */
static uint32_t read_varint(const uint8_t ** p, const uint8_t * end) {
    uint32_t v = 0;
    for (int shift = 0; *p < end && shift < 32; shift += 7) {
        uint8_t b = *(*p)++;
        v |= (uint32_t) (b & 0x7f) << shift;
        if (!(b & 0x80)) break;
    }
    return v;
}

// pass 0 only counts sites that are not `bl mk_address`; pass 1 patches.
static unsigned walk_sites(int pass, uintptr_t veneer, unsigned counts[2]) {
    const uint8_t * p = ff7_stack_sites + 8, * end = ff7_stack_sites + ff7_stack_sites_size;
    const uintptr_t text = so_mod.text_base, text_end = text + so_mod.text_size;
    unsigned n = 0;
    uintptr_t bl = text;
    while (p < end) {
        uint32_t v = read_varint(&p, end);
        bl += (v >> 1) * 2;
        int ok = bl + 4 <= text_end && decode_bl((uint16_t *) bl) == mk;
        if (pass == 0) {
            if (!ok) n++;
            continue;
        }
        if (!ok) continue;
        uint16_t code[2];
        if (veneer) encode_bl(code, veneer);
        else encode_add_k(code, stack_k);
        memcpy((void *) bl, code, sizeof(code));
        counts[v & 1]++;
        n++;
    }
    return n;
}

static void patch_sites(int check) {
    uint32_t count = 0;
    if (ff7_stack_sites_size < 8 || memcmp(ff7_stack_sites, "STK1", 4)) {
        l_warn("ff7_stack: site table missing or invalid");
        return;
    }
    memcpy(&count, ff7_stack_sites + 4, 4);

    SceUInt64 t0 = sceKernelGetProcessTimeWide();
    unsigned bad = walk_sites(0, 0, NULL);
    if (bad > MAX_BAD_SITES) {
        l_warn("ff7_stack: %u of %u sites differ from v1.0.29, stack accesses left alone", bad, count);
        return;
    }

    uintptr_t veneer = 0;
    if (check) {
        uintptr_t v = so_mod.text_base + VENEER;
        if (((uint32_t *) v)[0] != VENEER_CODE0 || ((uint32_t *) v)[1] != VENEER_CODE1) {
            l_warn("ff7_stack: unexpected code at the veneer, check mode off");
            return;
        }
        uint32_t code[2] = { 0xf000f8df, (uint32_t) &stack_check }; // ldr.w pc, [pc]; .word (as so_util's hooks)
        memcpy((void *) v, code, sizeof(code));
        veneer = v;
    }

    unsigned counts[2] = { 0, 0 };
    unsigned patched = walk_sites(1, veneer, counts);
    kuKernelFlushCaches((void *) so_mod.text_base, so_mod.text_size);
    l_info("ff7_stack: %u of %u stack mk_address calls %s (%u ESP, %u EBP; %u not matching) in %llu ms",
           patched, count, check ? "checked (stack_check.txt)" : "replaced by add.w",
           counts[0], counts[1], bad, (sceKernelGetProcessTimeWide() - t0) / 1000);
}

// start_ff7_core(entry, teb, stack_top, stack_size), on the game thread, once
static void start_hooked(uint32_t entry, uint32_t teb, uint32_t top, uint32_t size) {
    sceClibMemcpy((void *) start_hook.addr, start_hook.orig_instr, sizeof(start_hook.orig_instr));
    kuKernelFlushCaches((void *) start_hook.addr, sizeof(start_hook.orig_instr));

    if (top == STACK_TOP && size == STACK_SIZE) {
        if (map_stack()) patch_sites(file_exists(CHECK_SWITCH));
    } else {
        l_warn("ff7_stack: unexpected stack 0x%x+0x%x, stack accesses left alone", top - size, size);
    }
    ((void (*)(uint32_t, uint32_t, uint32_t, uint32_t)) start_hook.thumb_addr)(entry, teb, top, size);
}

void ff7_stack_report(double seconds) {
    if (!off_stack_calls || seconds <= 0) return;
    l_warn("ff7_stack: %llu calls off the stack at %d sites (check mode)", off_stack_calls, report_count);
    off_stack_calls = 0;
}

void ff7_stack_patch(void) {
    if (file_exists(OFF_SWITCH)) {
        l_info("ff7_stack: disabled by %s", OFF_SWITCH);
        return;
    }
    uintptr_t start = so_symbol(&so_mod, SYM_START);
    mk = so_symbol(&so_mod, SYM_MK_ADDRESS) & ~1;
    memmap = (uint32_t *) so_symbol(&so_mod, SYM_MEMMAP);
    if (!start || !memmap || mk != so_mod.text_base + MK_ADDRESS_OFFSET
        || *(uint32_t *) (start & ~1) != START_PROLOGUE) {
        l_warn("ff7_stack: unexpected .so layout, stack accesses left alone");
        return;
    }
    dummy_page = *(uint32_t *) (so_mod.text_base + DUMMY_GOT);
    start_hook = hook_addr(start, (uintptr_t) &start_hooked);
    l_info("ff7_stack: waiting for start_ff7_core (%u bytes of sites)", (unsigned) ff7_stack_sites_size);
}
