/*
 * x86 stack accesses without mk_address for libjni_ff7.so.
 *
 * Half of the 669,918 mk_address calls in the .so translate an address on the
 * x86 stack: ESP + c (push, pop, call arguments) or EBP + c (locals and
 * arguments of functions with a frame pointer). The stack is the one region
 * main_ff7() gives start_ff7_core(): VA 0x170000..0x190000 (128 KB). Only the
 * game thread runs recompiled code, so there is one x86 stack.
 *
 * Before start_ff7_core maps it, the stack is backed by a block allocated at
 * a fixed address H, with H - 0x170000 = K a Thumb-2 modified immediate
 * (0xXY000000): its MEMMAP entries are filled with H, so VA_newMapper, which
 * only fills empty entries, keeps them, and host = va + K for every stack
 * address. Every call site listed in ff7_stack_sites.bin
 * (scripts/gen-stack-sites.py: r0 provably ESP + c, or EBP + c in a function
 * where EBP is a frame pointer, |c| <= 0x8000) then gets
 *
 *     bl mk_address   ->   add.w r0, r0, #K
 *
 * A guard of 0x8000 bytes on each side of the stack keeps an access at
 * esp/ebp + c inside the block even at the stack's ends.
 *
 * Switches (DATA_PATH):
 *   stack_off.txt    leave everything as the original;
 *   stack_check.txt  instead of the add, each site calls stack_check(), which
 *                    returns what mk_address would and logs every site whose
 *                    address is not on the stack (it should never happen).
 *                    Slower: for validating the site list on the device.
 *
 * This software may be modified and distributed under the terms
 * of the MIT license. See the LICENSE file for details.
 */

